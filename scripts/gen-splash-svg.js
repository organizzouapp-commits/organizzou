// Generates src/components/organizzou/splash/splash-svg.ts from the two animated loading logos in public/brand/animada.
// The files animate through their own <style>; inlined, the same animation can be resumed (negative delay) and scoped.
const fs = require("fs")

function build(file, suffix) {
  let svg = fs.readFileSync(file, "utf8").trim()
  const m = svg.match(/<style>([\s\S]*?)<\/style>/)
  if (!m) throw new Error("no style in " + file)
  let css = m[1]
  // Keep keyframes, scope the rules, and make every start delay resumable: delay - var(--splash-elapsed).
  const rules = []
  const keyframes = []
  for (const line of css.split("\n").map((l) => l.trim()).filter(Boolean)) {
    if (line.startsWith("@keyframes")) keyframes.push(line.replace(/@keyframes (\w+)/, "@keyframes splash-$1"))
    else if (line.startsWith("@media")) continue
    else rules.push(line)
  }
  const out = []
  for (const rule of rules) {
    const sel = rule.slice(0, rule.indexOf("{")).trim()
    const body = rule.slice(rule.indexOf("{") + 1, rule.lastIndexOf("}"))
    const parts = body.split(";").map((p) => p.trim()).filter(Boolean)
    const next = []
    for (const part of parts) {
      if (part.startsWith("animation:")) {
        // animation:NAME DUR EASE [DELAY] [infinite|both]
        const tokens = part.slice("animation:".length).trim().split(/\s+/)
        const name = tokens[0]
        const dur = tokens[1]
        const infinite = tokens.includes("infinite")
        const rest = tokens.slice(2)
        const delay = rest.find((t) => /^\.?\d*\.?\d+s$/.test(t))
        const ease = rest.filter((t) => t !== delay && t !== "infinite" && t !== "both").join(" ")
        next.push(`animation-name:splash-${name}`, `animation-duration:${dur}`, `animation-timing-function:${ease}`, `animation-delay:calc(${delay ?? "0s"} - var(--splash-elapsed,0s))`, `animation-fill-mode:both`)
        if (infinite) next.push("animation-iteration-count:infinite")
      } else next.push(part)
    }
    const scoped = sel.split(",").map((s) => `.org-splash-logo ${s.trim().replace(/^\.loop /, "")}`).join(",")
    out.push(`${scoped}{${next.join(";")}}`)
  }
  const style = `<style>${out.join("")}${keyframes.join("")}html[data-splash-final] .org-splash-logo *{animation:none!important}@media (prefers-reduced-motion:reduce){.org-splash-logo *{animation:none!important}}</style>`
  svg = svg.replace(/<style>[\s\S]*?<\/style>/, () => style)
  // Unique ids per theme variant (both are in the document).
  svg = svg.replace(/id="tc"/g, `id="tc-${suffix}"`).replace(/id="wc"/g, `id="wc-${suffix}"`).replace(/url\(#tc\)/g, `url(#tc-${suffix})`).replace(/url\(#wc\)/g, `url(#wc-${suffix})`)
  // Decorative: the splash has its own status role.
  svg = svg.replace(' role="img" aria-label="Organizzou"', ' aria-hidden="true"').replace('class="loop"', 'class="org-splash-svg w-full h-auto"')
  return svg
}

const dark = build("public/brand/animada/organizzou-logo-carregamento-escuro.svg", "d")
const light = build("public/brand/animada/organizzou-logo-carregamento-claro.svg", "l")
const header = "// GENERATED by scripts/gen-splash-svg.js from public/brand/animada/organizzou-logo-carregamento-*.svg: do not edit by hand.\n// The same artwork as the files, inlined so CSS can resume the intro (animation-delay minus --splash-elapsed) and scope its rules.\n\n"
fs.mkdirSync("src/components/organizzou/splash", { recursive: true })
fs.writeFileSync("src/components/organizzou/splash/splash-svg.ts", `${header}export const SPLASH_SVG_DARK = ${JSON.stringify(dark)}\n\nexport const SPLASH_SVG_LIGHT = ${JSON.stringify(light)}\n`)
console.log("ok", dark.length, light.length)
